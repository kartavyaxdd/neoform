import { useEffect, useRef, useState } from "react";
import { ArrowRight, Check, Plus, Sparkles, Trash2 } from "lucide-react";
import * as D from "./domain";
import { saveChange, request, useStore } from "./store";
import {
  generationInput,
  auditGenerated,
  type ProgramAudit,
  validateGenerated,
  saveGenerated,
  type Generated,
  type GenerationInput,
} from "./generation";
import { geminiProofSchema, type GeminiProof } from "./aiProof";
import { Button, Field, Num } from "./ui";
export function AiWizard({ close }: { close: () => void }) {
  const store = useStore(),
    profile = store.box.data.profile;
  const [step, setStep] = useState(0),
    [input, setInput] = useState<GenerationInput>({
      goal: profile?.goal || "Build muscle",
      experience: profile?.experience || "New",
      days: Math.min(6, Math.max(2, profile?.days || 3)),
      minutes: 45,
      equipment: profile?.equipment || ["Dumbbell"],
      emphasis: "Balanced",
      limitation: "None",
      technique: "straight",
    }),
    [preview, setPreview] = useState<Generated | null>(null),
    [busy, setBusy] = useState(false),
    [saving, setSaving] = useState(false),
    [error, setError] = useState(""),
    [activate, setActivate] = useState(false),
    [proof, setProof] = useState("");
  const pending = useRef<{ id: string; controller: AbortController } | null>(
      null,
    ),
    mounted = useRef(true);
  const update = <K extends keyof GenerationInput>(
    key: K,
    value: GenerationInput[K],
  ) => setInput((x) => ({ ...x, [key]: value }));
  async function cancel() {
    const job = pending.current;
    pending.current = null;
    if (job) {
      void request("/ai/cancel", "POST", { requestId: job.id }).catch(() => {});
      job.controller.abort();
    }
    if (mounted.current) {
      setBusy(false);
      setError("Generation cancelled. Your preferences are kept.");
    }
  }
  useEffect(() => {
    mounted.current = true;
    return () => {
      mounted.current = false;
      void cancel();
    };
  }, []);
  async function generate() {
    setError("");
    setBusy(true);
    const id = D.uid(),
      controller = new AbortController();
    pending.current = { id, controller };
    const timeout = setTimeout(() => {
      void cancel();
      if (mounted.current) setError("Generation timed out. Try again.");
    }, 125000);
    try {
      const validated = generationInput.parse(input);
      const response = await request<{
        program: unknown;
        proof: GeminiProof;
      }>("/ai/generate", "POST", validated, {
        signal: controller.signal,
        headers: { "X-Neoform-Generation": id },
      });
      if (pending.current?.id !== id || !mounted.current) return;
      const p = validateGenerated(response.program, validated);
      const evidence = geminiProofSchema.safeParse(response.proof);
      if (!evidence.success)
        throw new Error("Invalid provider evidence. Please try again.");
      setPreview(p);
      setProof("Generated by Gemini · " + evidence.data.model);
      setStep(3);
    } catch (e) {
      if (!controller.signal.aborted && mounted.current)
        setError(
          (e as Error).name === "ZodError"
            ? "AI returned an invalid plan. Please try again."
            : (e as Error).message,
        );
    } finally {
      clearTimeout(timeout);
      if (pending.current?.id === id) pending.current = null;
      if (mounted.current) setBusy(false);
    }
  }
  function editTarget(
    wi: number,
    ti: number,
    key: string,
    value:
      | string
      | number
      | Generated["workouts"][number]["exercises"][number]["tempo"],
  ) {
    setPreview((p) =>
      p
        ? {
            ...p,
            workouts: p.workouts.map((w, i) =>
              i !== wi
                ? w
                : {
                    ...w,
                    exercises: w.exercises.map((t, j) =>
                      j !== ti ? t : { ...t, [key]: value },
                    ),
                  },
            ),
          }
        : null,
    );
  }
  let validReview = false;
  let audit: ProgramAudit | null = null;
  try {
    if (preview) {
      validateGenerated(preview, input);
      audit = auditGenerated(preview, input);
      validReview = true;
    }
  } catch {}
  return (
    <div className="ai-wizard">
      <div className="wizard-stepper" aria-label="Program maker steps">
        {["Focus", "Schedule", "Equipment", "Review"].map((label, i) => (
          <span
            key={label}
            className={i === step ? "current" : i < step ? "past" : ""}
          >
            <i>{i < step ? <Check size={12} /> : i + 1}</i>
            {label}
          </span>
        ))}
      </div>
      {busy ? (
        <div className="generation-loading" role="status">
          <Sparkles size={30} />
          <h3>Building your preview</h3>
          <p>Review the generated plan before saving.</p>
          <Button onClick={() => void cancel()}>Cancel generation</Button>
        </div>
      ) : step === 0 ? (
        <>
          <h3>What are you training for?</h3>
          <Field label="Goal">
            <select
              value={input.goal}
              onChange={(e) =>
                update("goal", e.target.value as GenerationInput["goal"])
              }
            >
              {["Build muscle", "Strength + muscle", "Consistency"].map((x) => (
                <option key={x}>{x}</option>
              ))}
            </select>
          </Field>
          <Field label="Experience">
            <select
              value={input.experience}
              onChange={(e) =>
                update(
                  "experience",
                  e.target.value as GenerationInput["experience"],
                )
              }
            >
              {["New", "Intermediate", "Advanced"].map((x) => (
                <option key={x}>{x}</option>
              ))}
            </select>
          </Field>
          <Field label="Technique preference">
            <select
              value={input.technique || "straight"}
              onChange={(e) =>
                update(
                  "technique",
                  e.target.value as GenerationInput["technique"],
                )
              }
            >
              <option value="straight">Straight sets (default)</option>
              <option value="tempo" disabled={input.experience === "New"}>
                Allow controlled tempo / pauses
              </option>
            </select>
          </Field>
          <p className="caption">
            Tempo needs explicit opt-in, experience and no declared movement
            limitation. Beginners stay with straight sets. AI supports straight
            sets and optional tempo only. Down-sets, supersets, pre-exhaust,
            myoreps, drop sets and giant sets require manual logger setup.
          </p>
        </>
      ) : step === 1 ? (
        <>
          <h3>Make room for training</h3>
          <Field label="Training days">
            <select
              value={input.days}
              onChange={(e) => update("days", Number(e.target.value))}
            >
              {[2, 3, 4, 5, 6].map((x) => (
                <option key={x} value={x}>
                  {x} days / week
                </option>
              ))}
            </select>
          </Field>
          <Field label="Session time">
            <select
              value={input.minutes}
              onChange={(e) =>
                update(
                  "minutes",
                  Number(e.target.value) as GenerationInput["minutes"],
                )
              }
            >
              {[30, 45, 60, 75].map((x) => (
                <option key={x} value={x}>
                  {x} minutes
                </option>
              ))}
            </select>
          </Field>
        </>
      ) : step === 2 ? (
        <>
          <h3>What can you use?</h3>
          <fieldset>
            <legend>Available equipment</legend>
            <div className="chips">
              {D.equipment.map((gear) => (
                <label
                  className={
                    "choice " +
                    (input.equipment.includes(gear) ? "selected" : "")
                  }
                  key={gear}
                >
                  <input
                    type="checkbox"
                    checked={input.equipment.includes(gear)}
                    onChange={() =>
                      update(
                        "equipment",
                        input.equipment.includes(gear)
                          ? input.equipment.filter((x) => x !== gear)
                          : [...input.equipment, gear],
                      )
                    }
                  />
                  {gear}
                </label>
              ))}
            </div>
          </fieldset>
          <div className="form-grid">
            <Field label="Emphasis">
              <select
                value={input.emphasis}
                onChange={(e) =>
                  update(
                    "emphasis",
                    e.target.value as GenerationInput["emphasis"],
                  )
                }
              >
                {["Balanced", ...D.majorMuscles].map((x) => (
                  <option key={x}>{x}</option>
                ))}
              </select>
            </Field>
            <Field label="Movement limitation">
              <select
                value={input.limitation}
                onChange={(e) =>
                  update(
                    "limitation",
                    e.target.value as GenerationInput["limitation"],
                  )
                }
              >
                {[
                  "None",
                  "Avoid overhead",
                  "Avoid deep knee bend",
                  "Avoid heavy hinges",
                ].map((x) => (
                  <option key={x}>{x}</option>
                ))}
              </select>
            </Field>
          </div>
          <p className="caption">
            Skip painful movements. This maker does not diagnose injuries.
          </p>
        </>
      ) : (
        preview && (
          <>
            <h3>Review your program</h3>
            <p className="caption">{proof}</p>
            <Field label="Generated program name">
              <input
                maxLength={80}
                value={preview.name}
                onChange={(e) =>
                  setPreview({ ...preview, name: e.target.value })
                }
              />
            </Field>
            <p className="preview-description">{preview.description}</p>
            <span className="tag">
              {preview.workouts.length} days · {preview.weeks} weeks · final
              week deload
            </span>
            {audit && (
              <details className="preview-workout" open>
                <summary>Program audit · {audit.policyVersion}</summary>
                <p className="caption">
                  Source-informed review, not a personalized physiological
                  assessment. Scientific Principles of Hypertrophy Training
                  (2020); citations are physical PDF pages from the supplied
                  book.
                </p>
                <ul>
                  {audit.warnings.map((w, i) => (
                    <li key={`${w.code}-${i}`}>
                      <p>
                        {w.message}{" "}
                        <small>
                          Source: physical PDF pp. {w.sourcePages.join(", ")}.
                        </small>
                      </p>
                    </li>
                  ))}
                </ul>
                <details>
                  <summary>
                    Planned muscle exposure (not measured growth)
                  </summary>
                  <ul>
                    {audit.muscles.map((m) => (
                      <li key={m.muscle}>
                        {m.muscle}: {m.directSets} direct sets ·{" "}
                        {m.indirectSets} supporting sets · {m.frequency} direct
                        exposures/week
                      </li>
                    ))}
                  </ul>
                </details>
              </details>
            )}
            {preview.workouts.map((w, wi) => (
              <details
                key={wi}
                className="preview-workout"
                open={wi === 0 || undefined}
              >
                <summary>
                  <span>
                    <b>{w.name}</b>
                    <small>
                      {w.exercises.length} exercises ·{" "}
                      {w.exercises.reduce((n, t) => n + t.sets, 0)} sets
                    </small>
                  </span>
                </summary>
                <Field label={`Generated workout ${wi + 1} name`}>
                  <input
                    maxLength={80}
                    value={w.name}
                    onChange={(e) =>
                      setPreview({
                        ...preview,
                        workouts: preview.workouts.map((x, i) =>
                          i === wi ? { ...x, name: e.target.value } : x,
                        ),
                      })
                    }
                  />
                </Field>
                {w.exercises.map((t, ti) => (
                  <details className="preview-movement" key={ti}>
                    <summary>
                      <span>
                        {D.catalog.find((e) => e.id === t.exerciseId)?.name}
                        <small>
                          {t.sets} × {t.min}–{t.max} · {t.rir} RIR ·{" "}
                          {t.technique === "tempo" && t.tempo
                            ? `Tempo ${t.tempo.eccentric}–${t.tempo.pause}–${t.tempo.concentric}s`
                            : "Straight sets"}
                        </small>
                      </span>
                    </summary>
                    <Field label={`Day ${wi + 1} exercise ${ti + 1}`}>
                      <select
                        value={t.exerciseId}
                        onChange={(e) =>
                          editTarget(wi, ti, "exerciseId", e.target.value)
                        }
                      >
                        {D.catalog
                          .filter((e) => input.equipment.includes(e.equipment))
                          .map((e) => (
                            <option value={e.id} key={e.id}>
                              {e.name}
                            </option>
                          ))}
                      </select>
                    </Field>
                    {t.technique === "tempo" && t.tempo && (
                      <>
                        <div className="review-targets">
                          {(["eccentric", "pause", "concentric"] as const).map(
                            (key) => (
                              <Field
                                key={key}
                                label={`Day ${wi + 1} exercise ${ti + 1} ${key} seconds`}
                              >
                                <Num
                                  label={`Day ${wi + 1} exercise ${ti + 1} ${key} seconds`}
                                  value={t.tempo![key]}
                                  min={key === "pause" ? 0 : 1}
                                  max={
                                    key === "eccentric"
                                      ? 5
                                      : key === "pause"
                                        ? 2
                                        : 3
                                  }
                                  onChange={(n) =>
                                    editTarget(wi, ti, "tempo", {
                                      ...t.tempo!,
                                      [key]: n,
                                    })
                                  }
                                />
                              </Field>
                            ),
                          )}
                        </div>
                        <Button
                          onClick={() => {
                            editTarget(wi, ti, "technique", "straight");
                            editTarget(wi, ti, "tempo", undefined);
                          }}
                        >
                          Use straight sets
                        </Button>
                      </>
                    )}
                    <div className="review-targets">
                      {(["sets", "min", "max", "rir", "rest"] as const).map(
                        (key) => (
                          <Field
                            key={key}
                            label={`Day ${wi + 1} exercise ${ti + 1} ${key}`}
                          >
                            <Num
                              label={`Day ${wi + 1} exercise ${ti + 1} ${key}`}
                              value={t[key]}
                              min={
                                key === "rir"
                                  ? 2
                                  : key === "rest"
                                    ? 45
                                    : key === "sets"
                                      ? 1
                                      : 5
                              }
                              max={
                                key === "sets" || key === "rir"
                                  ? 4
                                  : key === "rest"
                                    ? 180
                                    : 20
                              }
                              onChange={(n) => editTarget(wi, ti, key, n)}
                            />
                          </Field>
                        ),
                      )}
                    </div>
                    <Button
                      variant="ghost"
                      onClick={() =>
                        setPreview({
                          ...preview,
                          workouts: preview.workouts.map((x, i) =>
                            i !== wi
                              ? x
                              : {
                                  ...x,
                                  exercises: x.exercises.filter(
                                    (_, j) => j !== ti,
                                  ),
                                },
                          ),
                        })
                      }
                    >
                      <Trash2 size={15} />
                      Remove movement
                    </Button>
                  </details>
                ))}
                <Button
                  disabled={w.exercises.length >= 7}
                  onClick={() => {
                    const ex = D.catalog.find(
                      (e) =>
                        input.equipment.includes(e.equipment) &&
                        !w.exercises.some((t) => t.exerciseId === e.id),
                    );
                    if (ex)
                      setPreview({
                        ...preview,
                        workouts: preview.workouts.map((x, i) =>
                          i !== wi
                            ? x
                            : {
                                ...x,
                                exercises: [
                                  ...x.exercises,
                                  {
                                    exerciseId: ex.id,
                                    sets: 2,
                                    min: 8,
                                    max: 12,
                                    rir: 3,
                                    rest: 90,
                                  },
                                ],
                              },
                        ),
                      });
                  }}
                >
                  <Plus size={16} />
                  Add movement
                </Button>
              </details>
            ))}
            <label className="activate-choice">
              <input
                type="checkbox"
                checked={activate}
                onChange={(e) => setActivate(e.target.checked)}
              />
              <span>
                Activate this program
                <small>
                  Your existing programs and workout history stay saved.
                </small>
              </span>
            </label>
            {!validReview && (
              <p role="alert" className="error">
                Check targets, equipment and volume before saving.
              </p>
            )}
          </>
        )
      )}
      {error && (
        <p role="alert" className="error">
          {error}
        </p>
      )}
      {step === 3 && preview && error && (
        <Button
          onClick={() => {
            const url = URL.createObjectURL(
              new Blob([JSON.stringify({ input, program: preview }, null, 2)], {
                type: "application/json",
              }),
            );
            const link = document.createElement("a");
            link.href = url;
            link.download = "neoform-program-preview.json";
            link.click();
            setTimeout(() => URL.revokeObjectURL(url), 1000);
          }}
        >
          Export preview
        </Button>
      )}
      {!busy && (
        <div className="wizard-controls">
          {step > 0 && (
            <Button
              onClick={() => {
                setError("");
                setStep(step === 3 ? 2 : step - 1);
              }}
            >
              Back
            </Button>
          )}
          {step < 2 ? (
            <Button variant="primary" onClick={() => setStep(step + 1)}>
              Next
              <ArrowRight size={16} />
            </Button>
          ) : step === 2 ? (
            <Button
              variant="primary"
              disabled={!generationInput.safeParse(input).success}
              onClick={() => void generate()}
            >
              Generate preview
              <Sparkles size={16} />
            </Button>
          ) : (
            <Button
              variant="primary"
              disabled={!validReview || saving}
              onClick={() =>
                void (async () => {
                  setSaving(true);
                  try {
                    const p = validateGenerated(preview, input);
                    if (await saveChange((s) => saveGenerated(s, p, activate)))
                      close();
                    else
                      setError(
                        "Could not save on this device or online. Your preview is kept. Export it or retry saving.",
                      );
                  } catch {
                    setError("Check the edited plan before saving.");
                  } finally {
                    if (mounted.current) setSaving(false);
                  }
                })()
              }
            >
              {saving
                ? "Saving…"
                : activate
                  ? "Save and activate"
                  : "Save program"}
              <Check size={16} />
            </Button>
          )}
        </div>
      )}
      {step !== 3 && (
        <p className="caption ai-host-note">
          Requires your account's Gemini API key in More settings. Only bounded
          training preferences are sent to Google; API charges and quota limits
          may apply. Review the preview before saving.
        </p>
      )}
    </div>
  );
}
